// addErrorResponses attaches the shared error replies to every operation. The
// universal ones are always possible; the specific ones are derived from the
// error reasons the operation description names, so the document never claims
// a status an endpoint cannot produce.
func addErrorResponses(root *yaml.Node) {
	components := mapLookup(root, "components")
	responses := mapLookup(components, "responses")
	if responses == nil {
		responses = mapNode()
		mapSet(components, "responses", responses)
	}
	for _, r := range sharedResponses {
		mapSet(responses, r.name, r.node())
	}

	paths := mapLookup(root, "paths")
	for i := 0; i+1 < len(paths.Content); i += 2 {
		operations := paths.Content[i+1]
		for j := 0; j+1 < len(operations.Content); j += 2 {
			op := operations.Content[j+1]
			existing := mapLookup(op, "responses")
			if existing == nil {
				existing = mapNode()
				mapSet(op, "responses", existing)
			}
			description := ""
			if node := mapLookup(op, "description"); node != nil {
				description = node.Value
			}
			needed := map[string]bool{"401": true, "403": true, "500": true}
			id := ""
			if node := mapLookup(op, "operationId"); node != nil {
				id = node.Value
			}
			if _, public := publicOperations[id]; public {
				delete(needed, "401")
			}
			for reason, status := range reasonStatus {
				if strings.Contains(description, reason) {
					needed[status] = true
				}
			}
			// Walked in sorted order, not as a range over needed: map iteration
			// order would shuffle the shared error responses on every run, so
			// the published document would keep differing from itself.
			statuses := make([]string, 0, len(needed))
			for status := range needed {
				statuses = append(statuses, status)
			}
			sort.Strings(statuses)
			for _, status := range statuses {
				if mapLookup(existing, status) != nil {
					continue
				}
				ref, ok := errorResponses[status]
				if !ok {
					continue
				}
				mapSet(existing, status, respRef(ref))
			}
		}
	}
}

