// Command openapi enriches the gnostic generated document with the pieces it
// cannot express: the service description, the servers, the security schemes
// that authorise each operation, the shared error responses and the raw
// binary bindings that live outside the proto JSON codec.
//
// It is idempotent, so it can run after every `make api`, and it emits the
// document as YAML and as JSON together with a Swagger UI page that loads it.
//
//	go run ./tools/openapi -in openapi.yaml -out docs
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	in := flag.String("in", "openapi.yaml", "generated OpenAPI document to enrich")
	out := flag.String("out", "docs", "directory that receives the published copies")
	flag.Parse()

	doc, err := load(*in)
	if err != nil {
		log.Fatalf("openapi: %v", err)
	}
	root := doc.Content[0]

	enrich(root)
	addErrorSchema(root)
	addRawBindings(root)
	addErrorResponses(root)

	if err := writeYAML(*in, doc); err != nil {
		log.Fatalf("openapi: %v", err)
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatalf("openapi: %v", err)
	}
	for _, name := range []string{"openapi.yaml", "swagger.yaml"} {
		if err := writeYAML(filepath.Join(*out, name), doc); err != nil {
			log.Fatalf("openapi: %v", err)
		}
	}
	if err := writeJSON(filepath.Join(*out, "openapi.json"), root); err != nil {
		log.Fatalf("openapi: %v", err)
	}
	if err := os.WriteFile(filepath.Join(*out, "index.html"), []byte(swaggerPage), 0o644); err != nil {
		log.Fatalf("openapi: %v", err)
	}
	fmt.Printf("openapi: wrote %s and %s/{openapi.yaml,swagger.yaml,openapi.json,index.html}\n", *in, *out)
}

func load(path string) (*yaml.Node, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	if strings.Contains(string(raw), enrichmentMarker) {
		return nil, fmt.Errorf("%s is already enriched; run `make api` first so the document is regenerated from the proto files", path)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return nil, fmt.Errorf("%s is not a YAML document", path)
	}
	return &doc, nil
}

// enrichmentMarker is written into the header of the published document so a
// second run without a regeneration is refused instead of compounding.
const enrichmentMarker = "then enriched by tools/openapi"

func writeYAML(path string, doc *yaml.Node) error {
	var buf strings.Builder
	buf.WriteString("# Generated by protoc-gen-openapi, then enriched by tools/openapi.\n")
	buf.WriteString("# Do not edit by hand: run `make api && make docs` instead.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc.Content[0]); err != nil {
		return fmt.Errorf("encode %s: %w", path, err)
	}
	if err := enc.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(buf.String()), 0o644)
}

func writeJSON(path string, root *yaml.Node) error {
	raw, err := yaml.Marshal(root)
	if err != nil {
		return fmt.Errorf("re-encode for json: %w", err)
	}
	var plain any
	if err := yaml.Unmarshal(raw, &plain); err != nil {
		return fmt.Errorf("decode for json: %w", err)
	}
	out, err := json.MarshalIndent(normalise(plain), "", "  ")
	if err != nil {
		return fmt.Errorf("encode json: %w", err)
	}
	return os.WriteFile(path, append(out, '\n'), 0o644)
}

// normalise turns the YAML decoded value into something encoding/json accepts,
// where every map key has to be a string.
func normalise(value any) any {
	switch v := value.(type) {
	case map[string]any:
		out := make(map[string]any, len(v))
		for key, item := range v {
			out[key] = normalise(item)
		}
		return out
	case map[any]any:
		out := make(map[string]any, len(v))
		for key, item := range v {
			out[fmt.Sprint(key)] = normalise(item)
		}
		return out
	case []any:
		out := make([]any, len(v))
		for i, item := range v {
			out[i] = normalise(item)
		}
		return out
	default:
		return value
	}
}

// enrich adds the document level metadata, the security schemes and the
// per-operation security requirement.
func enrich(root *yaml.Node) {
	info := mapLookup(root, "info")
	if info == nil {
		info = mapNode()
		mapSet(root, "info", info)
	}
	mapSet(info, "title", str("Nagisa 网盘 API"))
	mapSet(info, "version", str("1.0.0"))
	mapSet(info, "description", literal(apiDescription))
	mapSet(info, "contact", mapNode(
		str("name"), str("Nagisa Netdisk"),
	))
	mapSet(info, "license", mapNode(str("name"), str("MIT")))

	mapSet(root, "servers", seq(
		mapNode(str("url"), str("http://127.0.0.1:8000"), str("description"), str("本地开发环境")),
	))

	mapSet(root, "tags", seq(
		mapNode(str("name"), str("AuthService"), str("description"), str("账号认证与会话管理：登录、刷新、退出、修改密码。除 GetAuthConfig 与 Login 外均需访问令牌。")),
		mapNode(str("name"), str("UserService"), str("description"), str("账号管理：仅持有 user_manage 权限且等级严格高于目标的账号可以创建、修改、禁用、删除账号并分配权限。")),
		mapNode(str("name"), str("NodeService"), str("description"), str("文件树：文件夹与文件统一为节点，共用描述、可见范围、访问名单与密码模型。")),
		mapNode(str("name"), str("FileService"), str("description"), str("内容传输：分片上传、签名下载地址、预览与打包下载。")),
		mapNode(str("name"), str("ShareService"), str("description"), str("分享链接：把节点以独立的能力集合发布给没有账号的访问者。AccessShare、ListShareChildren、GetShareDownloadUrl 为匿名接口。")),
		mapNode(str("name"), str("AuditService"), str("description"), str("审计日志：记录每一次状态变更及其结果，只增不改。")),
		mapNode(str("name"), str("SystemService"), str("description"), str("系统信息、存储统计、运行参数与维护任务。GetSystemInfo 与 HealthCheck 为匿名接口。")),
	))

	components := mapLookup(root, "components")
	if components == nil {
		components = mapNode()
		mapSet(root, "components", components)
	}
	mapSet(components, "securitySchemes", mapNode(
		str("bearerAuth"), mapNode(
			str("type"), str("http"),
			str("scheme"), str("bearer"),
			str("bearerFormat"), str("JWT"),
			str("description"), literal("访问令牌。先调用 AuthService.Login 取得 accessToken，再以 `Authorization: Bearer <token>` 发送。"),
		),
		str("nodeToken"), mapNode(
			str("type"), str("apiKey"),
			str("in"), str("header"),
			str("name"), str("X-Node-Token"),
			str("description"), literal("文件夹解锁令牌，由 NodeService.UnlockNode 返回。访问受密码保护的文件夹及其子节点时必须携带。"),
		),
		str("shareToken"), mapNode(
			str("type"), str("apiKey"),
			str("in"), str("header"),
			str("name"), str("X-Share-Token"),
			str("description"), literal("分享访问令牌，由 ShareService.AccessShare 返回，用于访问设有密码的分享链接。"),
		),
		str("requestId"), mapNode(
			str("type"), str("apiKey"),
			str("in"), str("header"),
			str("name"), str("X-Request-Id"),
			str("description"), literal("可选。调用方自带的链路标识，会写入审计日志并原样回显。"),
		),
	))

	mapSet(root, "security", seq(mapNode(str("bearerAuth"), seq())))

	// Anonymous endpoints must not advertise a bearer requirement, otherwise a
	// generated client would refuse to call them.
	paths := mapLookup(root, "paths")
	if paths == nil {
		return
	}
	for i := 0; i+1 < len(paths.Content); i += 2 {
		operations := paths.Content[i+1]
		for j := 0; j+1 < len(operations.Content); j += 2 {
			op := operations.Content[j+1]
			id := ""
			if node := mapLookup(op, "operationId"); node != nil {
				id = node.Value
			}
			if _, public := publicOperations[id]; public {
				mapSet(op, "security", seq())
				if desc := mapLookup(op, "description"); desc != nil {
					desc.Value = desc.Value + "\n\n本接口为公开接口，无需访问令牌。"
				}
			}
		}
	}
}

// addErrorSchema publishes the error envelope and the reason enumeration. The
// envelope is produced by the server's error encoder rather than by a proto
// message, so the generator cannot know about it.
func addErrorSchema(root *yaml.Node) {
	components := mapLookup(root, "components")
	schemas := mapLookup(components, "schemas")
	if schemas == nil {
		schemas = mapNode()
		mapSet(components, "schemas", schemas)
	}
	reasons := make([]*yaml.Node, 0, len(errorReasons))
	for _, reason := range errorReasons {
		reasons = append(reasons, str(reason))
	}
	mapSet(schemas, "netdisk.v1.Error", mapNode(
		str("type"), str("object"),
		str("description"), str("统一错误响应。reason 取自 ErrorReason 枚举，调用方应按其分支。"),
		str("required"), seq(str("code"), str("reason")),
		str("properties"), mapNode(
			str("code"), mapNode(str("type"), str("integer"), str("format"), str("int32"), str("description"), str("HTTP 状态码")),
			str("reason"), mapNode(str("type"), str("string"), str("description"), str("机器可读的错误原因"), str("enum"), seq(reasons...)),
			str("message"), mapNode(str("type"), str("string"), str("description"), str("人类可读的说明")),
			str("metadata"), mapNode(str("type"), str("object"), str("additionalProperties"), mapNode(str("type"), str("string")), str("description"), str("附加上下文")),
		),
	))
}

