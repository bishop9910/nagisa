// --- small YAML node helpers -------------------------------------------------

func str(value string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: value}
}

func literal(value string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: value, Style: yaml.LiteralStyle}
}

func boolean(value bool) *yaml.Node {
	v := "false"
	if value {
		v = "true"
	}
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: v}
}

func seq(items ...*yaml.Node) *yaml.Node {
	return &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: items}
}

func mapNode(pairs ...*yaml.Node) *yaml.Node {
	return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map", Content: pairs}
}

func keyed(key string, value *yaml.Node) *yaml.Node {
	return mapNode(str(key), value)
}

func mapLookup(node *yaml.Node, key string) *yaml.Node {
	if node == nil || node.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			return node.Content[i+1]
		}
	}
	return nil
}

func mapSet(node *yaml.Node, key string, value *yaml.Node) {
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			node.Content[i+1] = value
			return
		}
	}
	node.Content = append(node.Content, str(key), value)
}

func refSchema(name string) *yaml.Node {
	return mapNode(str("$ref"), str("#/components/schemas/"+name))
}

func respRef(name string) *yaml.Node {
	return mapNode(str("$ref"), str("#/components/responses/"+name))
}

func pathParam(name, description string) *yaml.Node {
	return mapNode(
		str("name"), str(name),
		str("in"), str("path"),
		str("required"), boolean(true),
		str("description"), str(description),
		str("schema"), mapNode(str("type"), str("string")),
	)
}

func queryParam(name, description string, required bool) *yaml.Node {
	return mapNode(
		str("name"), str(name),
		str("in"), str("query"),
		str("required"), boolean(required),
		str("description"), str(description),
		str("schema"), mapNode(str("type"), str("string")),
	)
}

func headerParam(name, description string, required bool) *yaml.Node {
	return mapNode(
		str("name"), str(name),
		str("in"), str("header"),
		str("required"), boolean(required),
		str("description"), str(description),
		str("schema"), mapNode(str("type"), str("string")),
	)
}
